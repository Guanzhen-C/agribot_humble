GENERATED_NOTICE = "Generated by agribot_vehicle_config_tools. Do not edit by hand."


def _number(value: float) -> str:
    if abs(value) < 5e-13:
        return "0"
    return f"{value:.12g}"


def _sequence(values: list[float]) -> str:
    return " ".join(_number(value) for value in values)


def _pose_text(pose: dict[str, Any]) -> str:
    return f"{_sequence(pose['xyz'])} {_sequence(pose['rpy'])}"


def _yaml_dump(path: Path, data: dict[str, Any]) -> None:
    path.write_text(
        f"# {GENERATED_NOTICE}\n"
        + yaml.safe_dump(data, allow_unicode=True, sort_keys=False),
        encoding="utf-8",
    )


def _sensor_map(config: dict[str, Any]) -> dict[str, dict[str, Any]]:
    return {sensor["id"]: sensor for sensor in config["sensors"]}


def _wheel_map(config: dict[str, Any]) -> dict[str, dict[str, Any]]:
    return {wheel["id"]: wheel for wheel in config["geometry"]["wheelCenters"]}


def generate_sensor_mounts(config: dict[str, Any]) -> dict[str, Any]:
    result: dict[str, Any] = {
        "vehicle_id": config["vehicleId"],
        "base_link_reference": config["baseFrame"]["reference"],
    }
    for sensor in config["sensors"]:
        pose = effective_sensor_pose(sensor)
        item = {
            "parent_frame": config["baseFrame"]["frameId"],
            "child_frame": sensor.get("measurementFrameId") or sensor["frameId"],
            "xyz": pose["xyz"],
            "rpy": pose["rpy"],
            "model": sensor["model"],
        }
        if sensor.get("role"):
            item["role"] = sensor["role"]
        result[sensor["id"]] = item
    return result


def generate_nav2_geometry(config: dict[str, Any]) -> dict[str, Any]:
    points = footprint(config)
    geometry = config["geometry"]
    navigation = config["navigation"]
    return {
        "/**": {
            "ros__parameters": {
                "vehicle_id": config["vehicleId"],
                "base_frame": config["baseFrame"]["frameId"],
                "footprint": points,
                "footprint_string": json.dumps(points, separators=(",", ":")),
                "inflation_radius": navigation["inflationRadiusM"],
                "cost_scaling_factor": navigation["costScalingFactor"],
                "motion_model": "Ackermann" if config["vehicleType"] == "ackermann" else "DiffDrive",
                "minimum_turning_radius": geometry["minTurningRadiusM"],
                "allow_reverse": navigation["allowReverse"],
                "max_linear_velocity": navigation["maxLinearSpeedMps"],
                "max_angular_velocity": navigation["maxAngularSpeedRadps"],
            }
        }
    }


