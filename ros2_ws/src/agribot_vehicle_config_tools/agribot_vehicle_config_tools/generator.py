def _sensor_visual(sensor: dict[str, Any]) -> str:
    sensor_type = sensor["sensorType"]
    if sensor_type == "lidar":
        geometry = "<cylinder radius=\"0.04\" length=\"0.08\"/>"
    elif sensor_type == "gnss_antenna":
        geometry = "<cylinder radius=\"0.0225\" length=\"0.036\"/>"
    elif sensor_type == "camera":
        geometry = "<box size=\"0.044 0.04 0.04\"/>"
    else:
        geometry = "<box size=\"0.05 0.04 0.015\"/>"
    return f"<geometry>{geometry}</geometry>"


def generate_urdf(config: dict[str, Any], sensor_visual_meshes: set[str] | None = None) -> str:
    geometry = config["geometry"]
    dynamics = config.get("dynamics", {})
    collision = config.get("collision", {})
    collision_center = collision.get("center", [0.0, 0.0, geometry["wheelRadiusM"]])
    collision_size = collision.get(
        "size",
        [
            geometry["bodyExtents"]["frontM"] + geometry["bodyExtents"]["rearM"],
            geometry["bodyExtents"]["leftM"] + geometry["bodyExtents"]["rightM"],
            geometry["wheelRadiusM"] * 2.0,
        ],
    )
    center_of_mass = dynamics.get("centerOfMass", collision_center)
    inertia = dynamics.get(
        "inertia",
        {"ixx": 1.0, "ixy": 0.0, "ixz": 0.0, "iyy": 1.0, "iyz": 0.0, "izz": 1.0},
    )
    body_visuals = []
    for visual in config.get("visuals", []):
        body_visuals.append(
            f"""    <visual name="{escape(visual['name'])}">
      <origin xyz="{_sequence(visual['pose']['xyz'])}" rpy="{_sequence(visual['pose']['rpy'])}"/>
      <geometry><mesh filename="{escape(visual['meshUri'])}" scale="{_sequence(visual.get('scale', [1.0, 1.0, 1.0]))}"/></geometry>
    </visual>"""
        )

    sensor_blocks = []
    integrated_visual = _integrated_visual(config)
    nominal_sensors = config.get("metadata", {}).get("calibrationState") == "unity_nominal_simulation_only"
    sensor_visual_meshes = sensor_visual_meshes or set()
    for sensor in config["sensors"]:
        pose = sensor["pose"]
        sensor_visual = (
            ""
            if integrated_visual and not nominal_sensors
            else f"\n    <visual>{_sensor_visual(sensor)}</visual>"
        )
        if sensor["id"] in sensor_visual_meshes:
            uri = escape(_visual_asset_uri(config, _sensor_visual_filename(sensor["id"])))
            sensor_visual = f'\n    <visual><geometry><mesh filename="{uri}"/></geometry></visual>'
        elif sensor["id"] == "rtk_secondary" and "rtk_master" in sensor_visual_meshes:
            # The master CAD export contains the shared mast and both antennas.
            sensor_visual = ""
        sensor_blocks.append(
            f"""  <link name="{escape(sensor['frameId'])}">{sensor_visual}
  </link>
  <joint name="{escape(sensor['id'])}_mount_joint" type="fixed">
    <origin xyz="{_sequence(pose['xyz'])}" rpy="{_sequence(pose['rpy'])}"/>
    <parent link="base_link"/><child link="{escape(sensor['frameId'])}"/>
  </joint>"""
        )
        if sensor.get("measurementFrameId"):
            measurement = sensor["measurementFramePose"]
            sensor_blocks.append(
                f"""  <link name="{escape(sensor['measurementFrameId'])}"/>
  <joint name="{escape(sensor['id'])}_measurement_joint" type="fixed">
    <origin xyz="{_sequence(measurement['xyz'])}" rpy="{_sequence(measurement['rpy'])}"/>
    <parent link="{escape(sensor['frameId'])}"/><child link="{escape(sensor['measurementFrameId'])}"/>
  </joint>"""
            )

    wheel_blocks = []
    for wheel in config["geometry"]["wheelCenters"]:
        wheel_id = wheel["id"]
        parent = "base_link"
        if wheel["steering"]:
            steering_link = f"{wheel_id}_steering_link"
            wheel_blocks.append(
                f"""  <link name="{steering_link}"/>
  <joint name="{wheel_id}_steering_joint" type="revolute">
    <origin xyz="{_sequence(wheel['position'])}" rpy="0 0 0"/>
    <parent link="base_link"/><child link="{steering_link}"/>
    <axis xyz="0 0 1"/>
    <limit lower="-{_number(_steering_joint_limit(config))}" upper="{_number(_steering_joint_limit(config))}" effort="200" velocity="1.5"/>
  </joint>"""
            )
            parent = steering_link
            origin = [0.0, 0.0, 0.0]
        else:
            origin = wheel["position"]
        wheel_visual = ""
        if integrated_visual and config["vehicleType"] == "tracked":
            wheel_visual = ""
        elif integrated_visual:
            wheel_uri = escape(
                _visual_asset_uri(config, _wheel_visual_filename(wheel_id))
            )
            wheel_visual = (
                f'\n    <visual><geometry><mesh filename="{wheel_uri}"/>'
                f"</geometry></visual>"
            )
        else:
            wheel_visual = (
                f'\n    <visual><origin rpy="1.570796326795 0 0"/>'
                f'<geometry><cylinder radius="{_number(_wheel_radius(config, wheel))}" '
                f'length="{_number(_wheel_width(config, wheel))}"/></geometry></visual>'
            )
        wheel_blocks.append(
            f"""  <link name="{wheel_id}_wheel_link">
{wheel_visual}
    <collision><origin rpy="1.570796326795 0 0"/><geometry><cylinder radius="{_number(_wheel_radius(config, wheel))}" length="{_number(_wheel_width(config, wheel))}"/></geometry></collision>
  </link>
  <joint name="{wheel_id}_wheel_joint" type="continuous">
    <origin xyz="{_sequence(origin)}" rpy="0 0 0"/>
    <parent link="{parent}"/><child link="{wheel_id}_wheel_link"/>
    <axis xyz="0 1 0"/>
  </joint>"""
        )

    urdf = f"""<?xml version="1.0"?>
<!-- {GENERATED_NOTICE} -->
<robot name="{escape(config['vehicleId'])}" xmlns:xacro="http://www.ros.org/wiki/xacro">
  <link name="base_link">
    <inertial>
      <origin xyz="{_sequence(center_of_mass)}" rpy="0 0 0"/>
      <mass value="{_number(dynamics.get('massKg', 50.0))}"/>
      <inertia ixx="{_number(inertia['ixx'])}" ixy="{_number(inertia['ixy'])}" ixz="{_number(inertia['ixz'])}" iyy="{_number(inertia['iyy'])}" iyz="{_number(inertia['iyz'])}" izz="{_number(inertia['izz'])}"/>
    </inertial>
    <collision><origin xyz="{_sequence(collision_center)}" rpy="0 0 0"/><geometry><box size="{_sequence(collision_size)}"/></geometry></collision>
{chr(10).join(body_visuals)}
  </link>
{chr(10).join(sensor_blocks)}
{chr(10).join(wheel_blocks)}
</robot>
"""
    if not config.get("implements") and not config.get("manipulators") and not caster_wheels(config) and not any(w.get("steeringAssembly") for w in config["geometry"]["wheelCenters"]) and not visual_rotors.rotors(config):
        return urdf
    robot = ET.fromstring(urdf)
    append_implements_urdf(robot, config)
    append_manipulator_urdf(robot, config)
    append_casters_urdf(robot, config)
    visual_rotors.append_urdf(robot, config)
    ET.indent(robot, space="  ")
    return '<?xml version="1.0"?>\n' + ET.tostring(robot, encoding="unicode") + "\n"


def generate_sdf(config: dict[str, Any], sensor_visual_meshes: set[str] | None = None) -> str:
    geometry = config["geometry"]
    navigation = config["navigation"]
    dynamics = config.get("dynamics", {})
    collision = config.get("collision", {})
    center = collision.get("center", [0.0, 0.0, geometry["wheelRadiusM"]])
    size = collision.get(
        "size",
        [
            geometry["bodyExtents"]["frontM"] + geometry["bodyExtents"]["rearM"],
            geometry["bodyExtents"]["leftM"] + geometry["bodyExtents"]["rightM"],
            geometry["wheelRadiusM"] * 2.0,
        ],
    )
    inertia = dynamics.get(
        "inertia",
        {"ixx": 1.0, "ixy": 0.0, "ixz": 0.0, "iyy": 1.0, "iyz": 0.0, "izz": 1.0},
    )
    visuals = []
    for visual in config.get("visuals", []):
        visuals.append(
            f"""      <visual name="{escape(visual['name'])}"><pose>{_pose_text(visual['pose'])}</pose><geometry><mesh><uri>{escape(visual['meshUri'])}</uri><scale>{_sequence(visual.get('scale', [1.0, 1.0, 1.0]))}</scale></mesh></geometry></visual>"""
        )

    sensors = _sensor_map(config)
    cad_visual_xml = "\n".join(ET.tostring(_cad_sensor_visual(config, sensor_id), encoding="unicode")
                               for sensor_id in sorted(sensor_visual_meshes or set()))
    imu = sensors["imu"]
    lidar = sensors["lidar"]
    camera = sensors["right_camera"]
    sensor_xml = f"""
      <sensor name="configured_imu" type="imu"><pose>{_pose_text(imu['pose'])}</pose><always_on>true</always_on><update_rate>{_number(imu.get('updateRateHz', 100.0))}</update_rate><plugin name="imu_controller" filename="libgazebo_ros_imu_sensor.so"><ros><remapping>~/out:={escape(imu.get('topic', '/imu/data'))}</remapping></ros><frame_name>{escape(imu['frameId'])}</frame_name></plugin></sensor>
      <sensor name="configured_c16" type="ray"><pose>{_pose_text(lidar['pose'])}</pose><always_on>true</always_on><update_rate>{_number(lidar.get('updateRateHz', 10.0))}</update_rate><ray><scan><horizontal><samples>2000</samples><resolution>1</resolution><min_angle>-3.14159265359</min_angle><max_angle>3.14159265359</max_angle></horizontal><vertical><samples>16</samples><resolution>1</resolution><min_angle>-0.279252680319</min_angle><max_angle>0.244346095279</max_angle></vertical></scan><range><min>0.3</min><max>100</max><resolution>0.01</resolution></range></ray><plugin name="c16_controller" filename="libgazebo_ros_velodyne_laser.so"><ros><remapping>~/out:={escape(lidar.get('topic', '/lidar/points'))}</remapping></ros><frame_name>{escape(lidar['frameId'])}</frame_name><organize_cloud>false</organize_cloud></plugin></sensor>
      <sensor name="configured_camera" type="camera"><pose>{_pose_text(camera['pose'])}</pose><always_on>true</always_on><update_rate>{_number(camera.get('updateRateHz', 10.0))}</update_rate><camera><horizontal_fov>0.936241091175</horizontal_fov><image><width>1280</width><height>1024</height><format>R8G8B8</format></image><clip><near>0.05</near><far>100</far></clip></camera><plugin name="camera_controller" filename="libgazebo_ros_camera.so"><ros><remapping>camera/image_raw:={escape(camera.get('topic', '/camera/rgb/image_raw'))}</remapping></ros><camera_name>camera</camera_name><frame_name>{escape(camera.get('measurementFrameId', camera['frameId']))}</frame_name></plugin></sensor>"""

    wheel_links = []
    wheel_joints = []
    integrated_visual = _integrated_visual(config)
    for wheel in geometry["wheelCenters"]:
        wheel_id = wheel["id"]
        if integrated_visual and config["vehicleType"] != "tracked":
            wheel_geometry = (
                "<mesh><uri>"
                + escape(_visual_asset_uri(config, _wheel_visual_filename(wheel_id)))
                + "</uri></mesh>"
            )
            wheel_visual_pose = "0 0 0 0 0 0"
        else:
            wheel_geometry = (
                f"<cylinder><radius>{_number(_wheel_radius(config, wheel))}</radius>"
                f"<length>{_number(_wheel_width(config, wheel))}</length></cylinder>"
            )
            wheel_visual_pose = "0 0 0 1.570796326795 0 0"
        wheel_visual = (
            f'<visual name="visual"><pose>{wheel_visual_pose}</pose>'
            f'<geometry>{wheel_geometry}</geometry></visual>'
            if not (integrated_visual and config["vehicleType"] == "tracked") else ""
        )
        wheel_links.append(
            f"""    <link name="{wheel_id}_wheel_link"><pose relative_to="__model__">{_sequence(wheel['position'])} 0 0 0</pose>{ET.tostring(_wheel_inertial(config, wheel), encoding='unicode')}<collision name="collision"><pose>0 0 0 1.570796326795 0 0</pose><geometry><cylinder><radius>{_number(_wheel_radius(config, wheel))}</radius><length>{_number(_wheel_width(config, wheel))}</length></cylinder></geometry></collision>{wheel_visual}</link>"""
        )
        if wheel["steering"]:
            steering_id = f"{wheel_id}_steering_link"
            wheel_links.append(
                f"    <link name=\"{steering_id}\"><pose relative_to=\"__model__\">{_sequence(wheel['position'])} 0 0 0</pose>{ET.tostring(_steering_inertial(config, wheel), encoding='unicode')}</link>"
            )
            wheel_joints.append(
                f"    <joint name=\"{wheel_id}_steering_joint\" type=\"revolute\"><pose relative_to=\"__model__\">{_sequence(wheel['position'])} 0 0 0</pose><parent>base_link</parent><child>{steering_id}</child><axis><xyz>0 0 1</xyz><limit><lower>-{_number(_steering_joint_limit(config))}</lower><upper>{_number(_steering_joint_limit(config))}</upper><effort>200</effort><velocity>1.5</velocity></limit></axis></joint>"
            )
            parent = steering_id
        else:
            parent = "base_link"
        wheel_joints.append(
            f"    <joint name=\"{wheel_id}_wheel_joint\" type=\"revolute\"><pose relative_to=\"__model__\">{_sequence(wheel['position'])} 0 0 0</pose><parent>{parent}</parent><child>{wheel_id}_wheel_link</child><axis><xyz>0 1 0</xyz><limit><lower>-1e16</lower><upper>1e16</upper><effort>{_number(dynamics.get('wheelTorqueNm', 200.0))}</effort><velocity>100</velocity></limit></axis></joint>"
        )

    sdf = f"""<sdf version="1.7">
  <!-- {GENERATED_NOTICE} -->
  <model name="{escape(config['vehicleId'])}">
    <allow_auto_disable>false</allow_auto_disable>
    <link name="base_link">
      <inertial><pose>{_sequence(dynamics.get('centerOfMass', center))} 0 0 0</pose><mass>{_number(dynamics.get('massKg', 50.0))}</mass><inertia><ixx>{_number(inertia['ixx'])}</ixx><ixy>{_number(inertia['ixy'])}</ixy><ixz>{_number(inertia['ixz'])}</ixz><iyy>{_number(inertia['iyy'])}</iyy><iyz>{_number(inertia['iyz'])}</iyz><izz>{_number(inertia['izz'])}</izz></inertia></inertial>
      <collision name="body_collision"><pose>{_sequence(center)} 0 0 0</pose><geometry><box><size>{_sequence(size)}</size></box></geometry></collision>
{chr(10).join(visuals)}
{cad_visual_xml}
{sensor_xml}
    </link>
{chr(10).join(wheel_links)}
{chr(10).join(wheel_joints)}
    <plugin name="ackermann_drive" filename="libagribot_ackermann_mppi_drive.so"><ros><namespace>/</namespace></ros><cmd_vel_topic>/nav2/cmd_vel</cmd_vel_topic><odom_topic>/odom</odom_topic><joint_state_topic>/joint_states</joint_state_topic><odom_frame>odom</odom_frame><base_frame>base_link</base_frame><wheelbase>{_number(geometry['wheelbaseM'])}</wheelbase><front_track_width>{_number(geometry['frontTrackM'])}</front_track_width><rear_track_width>{_number(geometry['rearTrackM'])}</rear_track_width><wheel_radius>{_number(geometry['wheelRadiusM'])}</wheel_radius><max_steering_angle>{_number(geometry['maxSteeringAngleRad'])}</max_steering_angle><max_steering_rate>{_number(dynamics.get('maxSteeringRateRadps', 1.2))}</max_steering_rate><max_speed>{_number(navigation['maxLinearSpeedMps'])}</max_speed><max_accel>{_number(dynamics.get('maxAccelerationMps2', 0.8))}</max_accel><command_timeout>0.5</command_timeout><publish_rate>30</publish_rate><publish_tf>false</publish_tf></plugin>
  </model>
</sdf>
"""
    if "wheelTorqueNm" in dynamics:
        root = ET.fromstring(sdf)
        plugin = root.find("./model/plugin[@name='ackermann_drive']")
        ET.SubElement(plugin, "wheel_torque").text = _number(dynamics["wheelTorqueNm"])
        sdf = ET.tostring(root, encoding="unicode") + "\n"
    if config["vehicleType"] != "ackermann":
        root = ET.fromstring(sdf)
        model = root.find("model")
        model.remove(model.find("./plugin[@name='ackermann_drive']"))
        _append_differential_plugins(model, config)
        append_implements_sdf(model, config)
        append_manipulator_sdf(model, config)
        append_casters_sdf(model, config)
        visual_rotors.append_sdf(model, config)
        visual_belts.append_sdf(model, config)
        ET.indent(root, space="  ")
        return ET.tostring(root, encoding="unicode") + "\n"
    if config.get("implements") or config.get("manipulators") or any(w.get("steeringAssembly") for w in geometry["wheelCenters"]):
        root = ET.fromstring(sdf)
        append_implements_sdf(root.find("model"), config)
        append_manipulator_sdf(root.find("model"), config)
        append_casters_sdf(root.find("model"), config)
        ET.indent(root, space="  ")
        return ET.tostring(root, encoding="unicode") + "\n"
    return sdf


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def generate_bundle(
    config: dict[str, Any],
    source: Path,
    output: Path,
    workspace_src: Path | None = None,
) -> dict[str, Any]:
    config_dir = output / "config"
    urdf_dir = output / "urdf"
    models_dir = output / "models"
    for directory in (config_dir, urdf_dir, models_dir):
        directory.mkdir(parents=True, exist_ok=True)
    unity_export_dir = source.parent
    sensor_visual_meshes = _sensor_visual_meshes(config, unity_export_dir)

    canonical_copy = output / "vehicle_config.json"
    canonical_copy.write_text(
        json.dumps(config, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    _yaml_dump(config_dir / "sensor_mounts.yaml", generate_sensor_mounts(config))
    _yaml_dump(config_dir / "nav2_geometry.yaml", generate_nav2_geometry(config))
    _yaml_dump(config_dir / "ackermann_kinematics.yaml", generate_kinematics(config))
    _yaml_dump(config_dir / "fastlivo_extrinsics.yaml", generate_fastlivo_config(config))
    (urdf_dir / f"{config['vehicleId']}.urdf.xacro").write_text(
        generate_urdf(config, sensor_visual_meshes), encoding="utf-8"
    )
    (models_dir / f"{config['vehicleId']}.sdf").write_text(
        generate_sdf(config, sensor_visual_meshes), encoding="utf-8"
    )

    unity_export_dir = source.parent
    unity_obj = unity_export_dir / "vehicle_visual.obj"
    visual_lod = None
    if unity_obj.is_file():
        body_grid = config.get("metadata", {}).get("simulationBodyLodGridM", SIMULATION_BODY_LOD_GRID_M)
        if isinstance(body_grid, bool) or not isinstance(body_grid, (float, int)) or not .001 <= body_grid <= SIMULATION_BODY_LOD_GRID_M:
            raise ValueError("simulationBodyLodGridM must be between 0.001 and 0.020 metres")
        if config["vehicleType"] == "tracked":
            # Tracks are one rigid visual shell; the supplied wheel anchors
            # define hidden contact rollers, not four visible tire meshes.
            shutil.copy2(unity_obj, models_dir / "vehicle_visual.obj")
        else:
            _split_integrated_visual_obj(unity_obj, models_dir)
        visual_lod = {
            "method": "material_aware_vertex_clustering",
            "bodyGridM": body_grid,
            "wheelGridM": SIMULATION_WHEEL_LOD_GRID_M,
            "body": _simplify_obj_vertex_clusters(
                models_dir / "vehicle_visual.obj",
                body_grid,
            ),
            "wheels": {},
        }
        for wheel_id in UNITY_WHEEL_OBJECTS.values():
            if not (models_dir / _wheel_visual_filename(wheel_id)).is_file():
                continue
            visual_lod["wheels"][wheel_id] = _simplify_obj_vertex_clusters(
                models_dir / _wheel_visual_filename(wheel_id),
                SIMULATION_WHEEL_LOD_GRID_M,
            )
    unity_mtl = unity_export_dir / "vehicle_visual.mtl"
    if unity_mtl.is_file():
        shutil.copy2(unity_mtl, models_dir / unity_mtl.name)
    for sensor_id in sorted(sensor_visual_meshes):
        mesh = unity_export_dir / _sensor_visual_filename(sensor_id)
        shutil.copy2(mesh, models_dir / mesh.name)
        shutil.copy2(mesh.with_suffix(".mtl"), models_dir / mesh.with_suffix(".mtl").name)

    visual_rotors.copy_assets(config, unity_export_dir, models_dir)
    visual_belts.copy_assets(config, unity_export_dir, models_dir)

    copy_implement_meshes(config, unity_export_dir, models_dir)
    copy_caster_meshes(config, unity_export_dir, models_dir)

    if workspace_src is not None:
        generate_runtime_files(config, source, workspace_src, output)

    generated_files = sorted(
        path for path in output.rglob("*") if path.is_file() and path.name != "manifest.json"
    )
    manifest = {
        "schemaVersion": "1.0",
        "vehicleId": config["vehicleId"],
        "sourceFile": source.name,
        "generator": "agribot_vehicle_config_tools 0.1.0",
        "coordinateConvention": "ROS_FLU",
        "runtimeTemplatesApplied": workspace_src is not None,
        "visualLod": visual_lod,
        "files": [
            {
                "path": str(path.relative_to(output)),
                "sizeBytes": path.stat().st_size,
                "sha256": _sha256(path),
            }
            for path in generated_files
        ],
    }
    (output / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    return manifest
