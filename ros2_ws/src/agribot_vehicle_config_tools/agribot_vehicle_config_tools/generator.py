def _patch_kf_gins(template: dict[str, Any], config: dict[str, Any]) -> dict[str, Any]:
    sensors = _sensor_map(config)
    imu_pose = effective_sensor_pose(sensors["imu"])
    antenna_pose = effective_sensor_pose(sensors["rtk_master"])
    parameters = template["rtk_eskf_localization"]["ros__parameters"]
    parameters["base_to_imu_m"] = imu_pose["xyz"]
    parameters["base_to_imu_rpy_rad"] = imu_pose["rpy"]
    parameters["antlever_m"] = [
        antenna_pose["xyz"][index] - imu_pose["xyz"][index] for index in range(3)
    ]
    return template


