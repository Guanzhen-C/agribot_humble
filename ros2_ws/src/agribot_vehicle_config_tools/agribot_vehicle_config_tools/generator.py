def _load_yaml(path: Path) -> dict[str, Any]:
    if not path.is_file():
        raise FileNotFoundError(f"ROS configuration template does not exist: {path}")
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def _patch_nav2(template: dict[str, Any], config: dict[str, Any]) -> dict[str, Any]:
    geometry = config["geometry"]
    navigation = config["navigation"]
    dynamics = config.get("dynamics", {})
    footprint_text = json.dumps(footprint(config), separators=(",", ":"))

    controller_server = template.get("controller_server")
    if controller_server is not None:
        follow_path = controller_server["ros__parameters"]["FollowPath"]
        follow_path["vx_max"] = navigation["maxLinearSpeedMps"]
        follow_path["vx_min"] = (
            -navigation["maxLinearSpeedMps"] if navigation["allowReverse"] else 0.0
        )
        follow_path["wz_max"] = navigation["maxAngularSpeedRadps"]
        follow_path["ax_max"] = dynamics.get(
            "maxAccelerationMps2", follow_path.get("ax_max", 0.8)
        )
        follow_path["ax_min"] = -follow_path["ax_max"]
        follow_path["motion_model"] = "Ackermann" if config["vehicleType"] == "ackermann" else "DiffDrive"
        follow_path.setdefault("AckermannConstraints", {})[
            "min_turning_r"
        ] = geometry["minTurningRadiusM"]
        if "PathAngleCritic" in follow_path:
            follow_path["PathAngleCritic"]["forward_preference"] = not navigation[
                "allowReverse"
            ]
        if "PreferForwardCritic" in follow_path:
            follow_path["PreferForwardCritic"]["enabled"] = not navigation[
                "allowReverse"
            ]

    for costmap_name in ("global_costmap", "local_costmap"):
        if costmap_name not in template:
            continue
        parameters = template[costmap_name][costmap_name]["ros__parameters"]
        parameters["footprint"] = footprint_text
        inflation = parameters.get("inflation_layer")
        if inflation is not None:
            inflation["inflation_radius"] = navigation["inflationRadiusM"]
            inflation["cost_scaling_factor"] = navigation["costScalingFactor"]

    planner_server = template.get("planner_server")
    if planner_server is not None:
        planner = planner_server["ros__parameters"]["GridBased"]
        planner["motion_model_for_search"] = (
            "REEDS_SHEPP" if navigation["allowReverse"] else "DUBIN"
        )
        planner["minimum_turning_radius"] = geometry["minTurningRadiusM"]
        if "analytic_expansion_max_length" in planner:
            planner["analytic_expansion_max_length"] = max(
                planner["analytic_expansion_max_length"],
                4.0 * geometry["minTurningRadiusM"],
            )
    return template


def _patch_simulation_nav2(
    template: dict[str, Any], config: dict[str, Any]
) -> dict[str, Any]:
    """Apply vehicle geometry and reject Gazebo returns on the lidar plane."""
    template = _patch_nav2(template, config)
    planner = template.get("planner_server", {}).get("ros__parameters", {}).get(
        "GridBased"
    )
    if planner is not None:
        # The configured simulation preplans all mandatory orchard waypoints in
        # one Smac request. Retain the validated long-route planning budget.
        planner["max_planning_time"] = max(
            float(planner.get("max_planning_time", 0.0)), 20.0
        )
    lidar_z = effective_sensor_pose(_sensor_map(config)["lidar"])["xyz"][2]
    navigation = config["navigation"]
    # Explicit base_link-relative bounds let taller CAD vehicles see obstacles
    # below a roof-mounted lidar. Keep existing profiles unchanged when omitted.
    min_obstacle_height = navigation.get("obstacleMinHeightM", lidar_z + 0.02)
    max_obstacle_height = navigation.get("obstacleMaxHeightM")

    for costmap_name in ("global_costmap", "local_costmap"):
        costmap = template.get(costmap_name)
        if costmap is None:
            continue
        parameters = costmap[costmap_name]["ros__parameters"]
        if costmap_name == "local_costmap":
            # A rear-axle origin can put the front corners outside a small
            # rolling map. Retain at least 2 m beyond the swept footprint.
            radius = max(math.hypot(x, y) for x, y in footprint(config))
            minimum_size = math.ceil(2.0 * (radius + 2.0))
            for dimension in ("width", "height"):
                if dimension in parameters:
                    parameters[dimension] = max(parameters[dimension], minimum_size)
        marking = parameters.get("stvl_layer", {}).get("lidar_mark")
        if marking is not None:
            marking["min_obstacle_height"] = min_obstacle_height
            if max_obstacle_height is not None:
                marking["max_obstacle_height"] = max_obstacle_height
    return template


