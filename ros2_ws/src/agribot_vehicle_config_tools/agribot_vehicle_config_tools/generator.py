def _sensor_visual(sensor: dict[str, Any]) -> str:
    sensor_type = sensor["sensorType"]
    if sensor_type == "lidar":
        geometry = "<cylinder radius=\"0.04\" length=\"0.08\"/>"
    elif sensor_type == "gnss_antenna":
        geometry = "<cylinder radius=\"0.0225\" length=\"0.036\"/>"
    elif sensor_type == "camera":
        geometry = "<box size=\"0.044 0.04 0.04\"/>"
    else:
        geometry = "<box size=\"0.05 0.04 0.015\"/>"
    return f"<geometry>{geometry}</geometry>"


def generate_urdf(config: dict[str, Any]) -> str:
    geometry = config["geometry"]
    dynamics = config.get("dynamics", {})
    collision = config.get("collision", {})
    collision_center = collision.get("center", [0.0, 0.0, geometry["wheelRadiusM"]])
    collision_size = collision.get(
        "size",
        [
            geometry["bodyExtents"]["frontM"] + geometry["bodyExtents"]["rearM"],
            geometry["bodyExtents"]["leftM"] + geometry["bodyExtents"]["rightM"],
            geometry["wheelRadiusM"] * 2.0,
        ],
    )
    center_of_mass = dynamics.get("centerOfMass", collision_center)
    inertia = dynamics.get(
        "inertia",
        {"ixx": 1.0, "ixy": 0.0, "ixz": 0.0, "iyy": 1.0, "iyz": 0.0, "izz": 1.0},
    )
    body_visuals = []
    for visual in config.get("visuals", []):
        body_visuals.append(
            f"""    <visual name="{escape(visual['name'])}">
      <origin xyz="{_sequence(visual['pose']['xyz'])}" rpy="{_sequence(visual['pose']['rpy'])}"/>
      <geometry><mesh filename="{escape(visual['meshUri'])}" scale="{_sequence(visual.get('scale', [1.0, 1.0, 1.0]))}"/></geometry>
    </visual>"""
        )

    sensor_blocks = []
    integrated_visual = _integrated_visual(config)
    for sensor in config["sensors"]:
        pose = sensor["pose"]
        sensor_visual = (
            ""
            if integrated_visual
            else f"\n    <visual>{_sensor_visual(sensor)}</visual>"
        )
        sensor_blocks.append(
            f"""  <link name="{escape(sensor['frameId'])}">{sensor_visual}
  </link>
  <joint name="{escape(sensor['id'])}_mount_joint" type="fixed">
    <origin xyz="{_sequence(pose['xyz'])}" rpy="{_sequence(pose['rpy'])}"/>
    <parent link="base_link"/><child link="{escape(sensor['frameId'])}"/>
  </joint>"""
        )
        if sensor.get("measurementFrameId"):
            measurement = sensor["measurementFramePose"]
            sensor_blocks.append(
                f"""  <link name="{escape(sensor['measurementFrameId'])}"/>
  <joint name="{escape(sensor['id'])}_measurement_joint" type="fixed">
    <origin xyz="{_sequence(measurement['xyz'])}" rpy="{_sequence(measurement['rpy'])}"/>
    <parent link="{escape(sensor['frameId'])}"/><child link="{escape(sensor['measurementFrameId'])}"/>
  </joint>"""
            )

    wheel_blocks = []
    for wheel in config["geometry"]["wheelCenters"]:
        wheel_id = wheel["id"]
        parent = "base_link"
        if wheel["steering"]:
            steering_link = f"{wheel_id}_steering_link"
            wheel_blocks.append(
                f"""  <link name="{steering_link}"/>
  <joint name="{wheel_id}_steering_joint" type="revolute">
    <origin xyz="{_sequence(wheel['position'])}" rpy="0 0 0"/>
    <parent link="base_link"/><child link="{steering_link}"/>
    <axis xyz="0 0 1"/>
    <limit lower="-{_number(geometry['maxSteeringAngleRad'])}" upper="{_number(geometry['maxSteeringAngleRad'])}" effort="200" velocity="1.5"/>
  </joint>"""
            )
            parent = steering_link
            origin = [0.0, 0.0, 0.0]
        else:
            origin = wheel["position"]
        wheel_visual = ""
        if integrated_visual:
            wheel_uri = escape(
                _visual_asset_uri(config, _wheel_visual_filename(wheel_id))
            )
            wheel_visual = (
                f'\n    <visual><geometry><mesh filename="{wheel_uri}"/>'
                f"</geometry></visual>"
            )
        else:
            wheel_visual = (
                f'\n    <visual><origin rpy="1.570796326795 0 0"/>'
                f'<geometry><cylinder radius="{_number(geometry["wheelRadiusM"])}" '
                f'length="{_number(geometry["wheelWidthM"])}"/></geometry></visual>'
            )
        wheel_blocks.append(
            f"""  <link name="{wheel_id}_wheel_link">
{wheel_visual}
    <collision><origin rpy="1.570796326795 0 0"/><geometry><cylinder radius="{_number(geometry['wheelRadiusM'])}" length="{_number(geometry['wheelWidthM'])}"/></geometry></collision>
  </link>
  <joint name="{wheel_id}_wheel_joint" type="continuous">
    <origin xyz="{_sequence(origin)}" rpy="0 0 0"/>
    <parent link="{parent}"/><child link="{wheel_id}_wheel_link"/>
    <axis xyz="0 1 0"/>
  </joint>"""
        )

    return f"""<?xml version="1.0"?>
<!-- {GENERATED_NOTICE} -->
<robot name="{escape(config['vehicleId'])}" xmlns:xacro="http://www.ros.org/wiki/xacro">
  <link name="base_link">
    <inertial>
      <origin xyz="{_sequence(center_of_mass)}" rpy="0 0 0"/>
      <mass value="{_number(dynamics.get('massKg', 50.0))}"/>
      <inertia ixx="{_number(inertia['ixx'])}" ixy="{_number(inertia['ixy'])}" ixz="{_number(inertia['ixz'])}" iyy="{_number(inertia['iyy'])}" iyz="{_number(inertia['iyz'])}" izz="{_number(inertia['izz'])}"/>
    </inertial>
    <collision><origin xyz="{_sequence(collision_center)}" rpy="0 0 0"/><geometry><box size="{_sequence(collision_size)}"/></geometry></collision>
{chr(10).join(body_visuals)}
  </link>
{chr(10).join(sensor_blocks)}
{chr(10).join(wheel_blocks)}
</robot>
"""


