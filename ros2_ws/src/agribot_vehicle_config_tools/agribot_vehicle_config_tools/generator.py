def _set_xml_text(parent: ET.Element, query: str, value: Any) -> None:
    element = parent.find(query)
    if element is None:
        raise ValueError(f"required SDF element is missing: {query}")
    element.text = str(value)


def generate_simulation_sdf(
    config: dict[str, Any], workspace_src: Path, unity_export_dir: Path
) -> str:
    simulation = workspace_src / "agribot_ackermann_mppi"
    vehicle_tree = ET.parse(simulation / "models" / "ackermann_scout.sdf")
    sensor_tree = ET.parse(simulation / "models" / "ackermann_scout_sensor.sdf")
    model = vehicle_tree.getroot().find("model")
    sensor_model = sensor_tree.getroot().find("model")
    if model is None or sensor_model is None:
        raise ValueError("Ackermann SDF templates must contain one model")
    model.set("name", config["vehicleId"])

    if config.get("metadata", {}).get("calibrationState") == "unity_nominal_simulation_only":
        ET.SubElement(model, "plugin", name="configured_sensor_collision_filter",
                      filename="libagribot_simulation_sensor_collision_filter.so")

    geometry = config["geometry"]
    navigation = config["navigation"]
    dynamics = config.get("dynamics", {})
    collision = config.get("collision", {})
    base = model.find("./link[@name='base_link']")
    sensor_base = sensor_model.find("./link[@name='base_link']")
    if base is None or sensor_base is None:
        raise ValueError("Ackermann SDF templates must contain base_link")

    center = collision.get("center", dynamics.get("centerOfMass", [0.0, 0.0, 0.0]))
    size = collision.get("size")
    _set_xml_text(base, "./inertial/pose", f"{_sequence(dynamics.get('centerOfMass', center))} 0 0 0")
    _set_xml_text(base, "./inertial/mass", _number(dynamics.get("massKg", 50.0)))
    inertia = dynamics.get("inertia", {})
    for key in ("ixx", "ixy", "ixz", "iyy", "iyz", "izz"):
        _set_xml_text(base, f"./inertial/inertia/{key}", _number(inertia.get(key, 0.0)))
    _set_xml_text(base, "./collision/pose", f"{_sequence(center)} 0 0 0")
    if size is not None:
        _set_xml_text(base, "./collision/geometry/box/size", _sequence(size))

    unity_mesh = unity_export_dir / "vehicle_visual.obj"
    if unity_mesh.is_file():
        body_visual = base.find("./visual[@name='vehicle_body_visual']")
        if body_visual is not None:
            _set_xml_text(body_visual, "./pose", "0 0 0 0 0 0")
            _set_xml_text(
                body_visual,
                "./geometry/mesh/uri",
                config["visuals"][0]["meshUri"],
            )

        # The Unity OBJ contains the configured body and wheel geometry.
        # Sensor housings are excluded to avoid camera self-occlusion.
        # Keep the physical wheel links and sensor
        # elements below, but remove their legacy visuals to avoid rendering
        # both the old placeholder model and the Unity vehicle.
        for visual in list(base.findall("visual")):
            if visual is not body_visual:
                base.remove(visual)
        for wheel_id in _wheel_map(config):
            wheel_link = model.find(f"./link[@name='{wheel_id}_wheel_link']")
            if wheel_link is not None:
                for visual in list(wheel_link.findall("visual")):
                    wheel_link.remove(visual)
                if config["vehicleType"] == "tracked":
                    continue
                wheel_visual = ET.SubElement(
                    wheel_link, "visual", {"name": "wheel_visual"}
                )
                geometry_xml = ET.SubElement(wheel_visual, "geometry")
                mesh_xml = ET.SubElement(geometry_xml, "mesh")
                ET.SubElement(mesh_xml, "uri").text = _visual_asset_uri(
                    config, _wheel_visual_filename(wheel_id)
                )

    wheel_map = _wheel_map(config)
    for wheel_id, wheel in wheel_map.items():
        pose = f"{_sequence(wheel['position'])} 0 0 0"
        _set_xml_text(model, f"./link[@name='{wheel_id}_wheel_link']/pose", pose)
        _set_xml_text(model, f"./joint[@name='{wheel_id}_wheel_joint']/pose", pose)
        if "wheelTorqueNm" in dynamics:
            _set_xml_text(model, f"./joint[@name='{wheel_id}_wheel_joint']/axis/limit/effort",
                          _number(dynamics["wheelTorqueNm"]))
        if wheel["steering"]:
            _set_xml_text(model, f"./link[@name='{wheel_id}_steering_link']/pose", pose)
            _set_xml_text(model, f"./joint[@name='{wheel_id}_steering_joint']/pose", pose)
            _set_xml_text(
                model,
                f"./joint[@name='{wheel_id}_steering_joint']/axis/limit/lower",
                _number(-_steering_joint_limit(config)),
            )
            _set_xml_text(
                model,
                f"./joint[@name='{wheel_id}_steering_joint']/axis/limit/upper",
                _number(_steering_joint_limit(config)),
            )
        wheel_link = model.find(f"./link[@name='{wheel_id}_wheel_link']")
        _set_xml_text(wheel_link, "./collision/geometry/cylinder/radius", _number(_wheel_radius(config, wheel)))
        _set_xml_text(wheel_link, "./collision/geometry/cylinder/length", _number(_wheel_width(config, wheel)))
        contact = config.get("metadata", {}).get("simulationSkidContact")
        if contact is not None:
            if config["vehicleType"] == "ackermann" or not isinstance(contact, dict):
                raise ValueError("simulationSkidContact requires a differential or tracked vehicle")
            axle_key = "frontLateralFriction" if wheel_id.startswith("front_") else "rearLateralFriction"
            for key in ("lateralFriction", "longitudinalFriction", *([axle_key] if axle_key in contact else [])):
                value = contact.get(key)
                if type(value) not in (float, int) or not math.isfinite(value) or value <= 0:
                    raise ValueError("simulationSkidContact friction must be finite and positive")
            # Cylinder local Z is the axle, unchanged by wheel rotation. Keep
            # the lower skid friction lateral and traction longitudinal.
            friction = "./collision/surface/friction/ode/"
            _set_xml_text(wheel_link, friction + "fdir1", "0 0 1")
            _set_xml_text(wheel_link, friction + "mu", _number(contact.get(axle_key, contact["lateralFriction"])))
            _set_xml_text(wheel_link, friction + "mu2", _number(contact["longitudinalFriction"]))
            if "lateralSlipMpsPerN" in contact:
                slip = contact["lateralSlipMpsPerN"]
                if type(slip) not in (float, int) or not math.isfinite(slip) or slip < 0:
                    raise ValueError("simulationSkidContact lateral slip must be finite and nonnegative")
                ode = wheel_link.find("./collision/surface/friction/ode")
                slip_node = ode.find("slip1")
                if slip_node is None:
                    slip_node = ET.SubElement(ode, "slip1")
                slip_node.text = _number(slip)
        if "massKg" in wheel:
            # Optional nominal cylinder inertia for imported vehicles. Do not
            # change the already validated small-vehicle template implicitly.
            wheel_link.remove(wheel_link.find("inertial"))
            wheel_link.append(_wheel_inertial(config, wheel))
        if wheel["steering"] and "steeringMassKg" in wheel:
            steering_link = model.find(f"./link[@name='{wheel_id}_steering_link']")
            steering_link.remove(steering_link.find("inertial"))
            steering_link.append(_steering_inertial(config, wheel))
        if config["vehicleType"] != "ackermann":
            _set_xml_text(model, f"./joint[@name='{wheel_id}_wheel_joint']/parent", "base_link")
            for tag, name in (("link", f"{wheel_id}_steering_link"), ("joint", f"{wheel_id}_steering_joint")):
                element = model.find(f"./{tag}[@name='{name}']")
                if element is not None:
                    model.remove(element)

    plugin = model.find("./plugin[@name='ackermann_drive']")
    if plugin is None:
        raise ValueError("Ackermann drive plugin is missing from SDF template")
    plugin_values = {
        "wheelbase": geometry["wheelbaseM"],
        "front_track_width": geometry["frontTrackM"],
        "rear_track_width": geometry["rearTrackM"],
        "wheel_radius": geometry["wheelRadiusM"],
        "max_steering_angle": geometry["maxSteeringAngleRad"],
        "max_steering_rate": dynamics.get("maxSteeringRateRadps", 1.2),
        "max_speed": navigation["maxLinearSpeedMps"],
        "max_accel": dynamics.get("maxAccelerationMps2", 0.8),
        "wheel_torque": dynamics.get("wheelTorqueNm", 200.0),
    }
    for key, value in plugin_values.items():
        _set_xml_text(plugin, key, _number(value))
    if config["vehicleType"] != "ackermann":
        model.remove(plugin)
        _append_differential_plugins(model, config)

    sensor_names = {
        "imu": "n300pro_imu",
        "lidar": "lslidar_c16_points",
        "right_camera": "hikrobot_right_camera",
    }
    sensors = _sensor_map(config)
    for sensor_id in sorted(_sensor_visual_meshes(config, unity_export_dir)):
        base.append(_cad_sensor_visual(config, sensor_id))
    for sensor_id, sdf_name in sensor_names.items():
        sensor_xml = sensor_base.find(f"./sensor[@name='{sdf_name}']")
        if sensor_xml is None:
            raise ValueError(f"sensor is missing from SDF template: {sdf_name}")
        sensor = sensors[sensor_id]
        _set_xml_text(sensor_xml, "pose", _pose_text(sensor["pose"]))
        _set_xml_text(sensor_xml, "update_rate", _number(sensor.get("updateRateHz", 10.0)))
        base.append(sensor_xml)

    append_implements_sdf(model, config)
    append_manipulator_sdf(model, config)
    append_casters_sdf(model, config)
    visual_rotors.append_sdf(model, config)
    visual_belts.append_sdf(model, config)
    ET.indent(vehicle_tree, space="  ")
    return ET.tostring(vehicle_tree.getroot(), encoding="unicode") + "\n"


def _append_differential_plugins(model: ET.Element, config: dict[str, Any]) -> None:
    drive = ET.SubElement(model, "plugin", name="configured_diff_drive", filename="libgazebo_ros_diff_drive.so")
    ros = ET.SubElement(drive, "ros")
    ET.SubElement(ros, "namespace").text = "/"
    ET.SubElement(ros, "remapping").text = "cmd_vel:=/nav2/cmd_vel"
    wheel_map = _wheel_map(config)
    # Existing four-wheel vehicles keep their established plugin settings.
    axles = [axle for axle in ("front", "rear")
             if not caster_wheels(config) or wheel_map[f"{axle}_left"]["driven"]]
    wheel_acceleration = config.get("metadata", {}).get("simulationDiffDriveWheelAccelerationMps2",
        config.get("dynamics", {}).get("maxAccelerationMps2", 0.8))
    if type(wheel_acceleration) not in (int, float) or not math.isfinite(wheel_acceleration) or wheel_acceleration < 0:
        raise ValueError("Simulation wheel acceleration must be finite and nonnegative")
    values = {"num_wheel_pairs": len(axles), "update_rate": 100,
              "max_wheel_torque": config.get("dynamics", {}).get("wheelTorqueNm", 200),
              "max_wheel_acceleration": wheel_acceleration,
              "publish_odom": "true", "publish_odom_tf": "false", "publish_wheel_tf": "false",
              "odometry_frame": "odom", "robot_base_frame": "base_link"}
    for key, value in values.items():
        ET.SubElement(drive, key).text = str(value)
    for axle in axles:
        for side in ("left", "right"):
            ET.SubElement(drive, f"{side}_joint").text = f"{axle}_{side}_wheel_joint"
        ET.SubElement(drive, "wheel_separation").text = _number(config["geometry"][f"{axle}TrackM"])
        wheel = _wheel_map(config)[f"{axle}_left"]
        ET.SubElement(drive, "wheel_diameter").text = _number(2 * _wheel_radius(config, wheel))
    joint_states = ET.SubElement(model, "plugin", name="configured_joint_states", filename="libgazebo_ros_joint_state_publisher.so")
    ET.SubElement(joint_states, "update_rate").text = "30"
    for wheel_id in _wheel_map(config):
        ET.SubElement(joint_states, "joint_name").text = f"{wheel_id}_wheel_joint"
    for wheel in caster_wheels(config):
        ET.SubElement(joint_states, "joint_name").text = f"{wheel['id']}_caster_joint"
    ground_truth = ET.SubElement(model, "plugin", name="configured_ground_truth", filename="libgazebo_ros_p3d.so")
    ros = ET.SubElement(ground_truth, "ros")
    ET.SubElement(ros, "remapping").text = "odom:=base_pose_ground_truth"
    ET.SubElement(ground_truth, "body_name").text = "base_link"
    ET.SubElement(ground_truth, "update_rate").text = "100"


