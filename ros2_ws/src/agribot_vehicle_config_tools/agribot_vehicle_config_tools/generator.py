GENERATED_NOTICE = "Generated by agribot_vehicle_config_tools. Do not edit by hand."
UNITY_WHEEL_OBJECTS = {
    "FLwheel": "front_left",
    "FRwheel": "front_right",
    "RLwheel": "rear_left",
    "RRwheel": "rear_right",
}
SIMULATION_BODY_LOD_GRID_M = 0.020
SIMULATION_WHEEL_LOD_GRID_M = 0.010
SIMULATION_LOD_NORMAL_BINS = 4


def _number(value: float) -> str:
    if abs(value) < 5e-13:
        return "0"
    return f"{value:.12g}"


def _sequence(values: list[float]) -> str:
    return " ".join(_number(value) for value in values)


def _pose_text(pose: dict[str, Any]) -> str:
    return f"{_sequence(pose['xyz'])} {_sequence(pose['rpy'])}"


def _yaml_dump(path: Path, data: dict[str, Any]) -> None:
    path.write_text(
        f"# {GENERATED_NOTICE}\n"
        + yaml.safe_dump(data, allow_unicode=True, sort_keys=False),
        encoding="utf-8",
    )


def _sensor_map(config: dict[str, Any]) -> dict[str, dict[str, Any]]:
    return {sensor["id"]: sensor for sensor in config["sensors"]}


def _wheel_map(config: dict[str, Any]) -> dict[str, dict[str, Any]]:
    return {wheel["id"]: wheel for wheel in config["geometry"]["wheelCenters"]}


def _integrated_visual(config: dict[str, Any]) -> bool:
    return any(
        visual.get("meshUri", "").endswith("/vehicle_visual.obj")
        for visual in config.get("visuals", [])
    )


def _visual_asset_uri(config: dict[str, Any], filename: str) -> str:
    mesh_uri = config["visuals"][0]["meshUri"]
    return f"{mesh_uri.rsplit('/', 1)[0]}/{filename}"


def _wheel_visual_filename(wheel_id: str) -> str:
    return f"{wheel_id}_wheel_visual.obj"


def _sensor_visual_filename(sensor_id: str) -> str:
    return f"sensor_{sensor_id}_visual.obj"


def _sensor_visual_meshes(config: dict[str, Any], export_dir: Path) -> set[str]:
    result = set()
    for sensor in config["sensors"]:
        mesh = export_dir / _sensor_visual_filename(sensor["id"])
        material = mesh.with_suffix(".mtl")
        if mesh.is_file() != material.is_file():
            raise ValueError(f"Incomplete sensor CAD export: {mesh.name}")
        if mesh.is_file():
            result.add(sensor["id"])
    return result


def _cad_sensor_visual(config: dict[str, Any], sensor_id: str) -> ET.Element:
    visual = ET.Element("visual", name=f"{sensor_id}_cad_visual")
    ET.SubElement(visual, "pose").text = _pose_text(_sensor_map(config)[sensor_id]["pose"])
    mesh = ET.SubElement(ET.SubElement(visual, "geometry"), "mesh")
    ET.SubElement(mesh, "uri").text = _visual_asset_uri(config, _sensor_visual_filename(sensor_id))
    ET.SubElement(visual, "plugin", name=f"{sensor_id}_visual_only",
                  filename="libagribot_simulation_sensor_visual.so")
    return visual


def _wheel_object(name: str) -> str | None:
    return UNITY_WHEEL_OBJECTS.get(name.split("__", 1)[0])


def _wheel_radius(config: dict[str, Any], wheel: dict[str, Any]) -> float:
    return wheel.get("radiusM") or config["geometry"]["wheelRadiusM"]


def _wheel_width(config: dict[str, Any], wheel: dict[str, Any]) -> float:
    return wheel.get("widthM") or config["geometry"]["wheelWidthM"]


def _steering_joint_limit(config: dict[str, Any]) -> float:
    geometry = config["geometry"]
    limit = geometry["maxSteeringAngleRad"]
    metadata = config.get("metadata", {})
    if (config["vehicleType"] == "ackermann"
            and (metadata.get("authoringTool") == "inspected_local_CAD_profile"
                 or bool(metadata.get("nominalDimensions")))
            and metadata.get("calibrationState") == "unity_nominal_simulation_only"):
        # The drive plugin splits a virtual bicycle angle into inner/outer wheel
        # angles. A wide tractor's inner joint must admit that same command.
        radius = geometry["wheelbaseM"] / math.tan(limit)
        inner_radius = max(radius - geometry["frontTrackM"] * 0.5, 1e-4)
        return math.atan2(geometry["wheelbaseM"], inner_radius)
    return limit


def _wheel_inertial(config: dict[str, Any], wheel: dict[str, Any]) -> ET.Element:
    mass, transverse, axial = 3., .01223, .02438
    if "massKg" in wheel:
        mass = wheel["massKg"]
        radius, width = _wheel_radius(config, wheel), _wheel_width(config, wheel)
        transverse = mass * (3 * radius ** 2 + width ** 2) / 12
        axial = mass * radius ** 2 / 2
    inertial = ET.Element("inertial")
    ET.SubElement(inertial, "mass").text = _number(mass)
    tensor = ET.SubElement(inertial, "inertia")
    for key, value in (("ixx", transverse), ("iyy", axial), ("izz", transverse)):
        ET.SubElement(tensor, key).text = _number(value)
    return inertial


def _steering_inertial(config: dict[str, Any], wheel: dict[str, Any]) -> ET.Element:
    mass, diagonal = .2, .0001
    if "steeringMassKg" in wheel:
        mass = wheel["steeringMassKg"]
        diagonal = mass * (.4 * _wheel_radius(config, wheel)) ** 2 / 6
    inertial = ET.Element("inertial")
    ET.SubElement(inertial, "mass").text = _number(mass)
    tensor = ET.SubElement(inertial, "inertia")
    for key in ("ixx", "iyy", "izz"):
        ET.SubElement(tensor, key).text = _number(diagonal)
    return inertial


def _scan_wheel_mesh_centers(source: Path) -> dict[str, list[float]]:
    bounds = {
        wheel_id: {"min": [math.inf] * 3, "max": [-math.inf] * 3, "faces": 0}
        for wheel_id in UNITY_WHEEL_OBJECTS.values()
    }
    current_wheel = None
    with source.open(encoding="utf-8", errors="strict") as stream:
        for line in stream:
            if line.startswith("o "):
                current_wheel = _wheel_object(line[2:].strip())
            elif current_wheel is not None and line.startswith("v "):
                values = [float(value) for value in line.split()[1:4]]
                for axis, value in enumerate(values):
                    bounds[current_wheel]["min"][axis] = min(
                        bounds[current_wheel]["min"][axis], value
                    )
                    bounds[current_wheel]["max"][axis] = max(
                        bounds[current_wheel]["max"][axis], value
                    )
            elif current_wheel is not None and line.startswith("f "):
                bounds[current_wheel]["faces"] += 1

    centers = {}
    for wheel_id, item in bounds.items():
        if item["faces"] == 0 or not all(math.isfinite(v) for v in item["min"]):
            expected = next(
                name for name, mapped_id in UNITY_WHEEL_OBJECTS.items()
                if mapped_id == wheel_id
            )
            raise ValueError(f"Unity OBJ is missing wheel mesh object: {expected}")
        centers[wheel_id] = [
            (minimum + maximum) * 0.5
            for minimum, maximum in zip(item["min"], item["max"])
        ]
    return centers


def _local_obj_face(line: str, vertex_base: int, uv_base: int, normal_base: int) -> str:
    result = []
    for token in line.split()[1:]:
        parts = token.split("/")
        bases = (vertex_base, uv_base, normal_base)
        converted = []
        for index, value in enumerate(parts):
            if not value:
                converted.append("")
                continue
            numeric = int(value)
            if numeric <= bases[index]:
                raise ValueError(f"wheel OBJ face references an external index: {token}")
            converted.append(str(numeric - bases[index]))
        result.append("/".join(converted))
    return "f " + " ".join(result) + "\n"


def _split_integrated_visual_obj(source: Path, output_dir: Path) -> None:
    """Keep wheels out of the body OBJ and export one joint-local OBJ per wheel."""
    centers = _scan_wheel_mesh_centers(source)
    output_dir.mkdir(parents=True, exist_ok=True)
    body_target = output_dir / "vehicle_visual.obj"
    body_temporary = output_dir / ".vehicle_visual.obj.tmp"
    wheel_targets = {
        wheel_id: output_dir / _wheel_visual_filename(wheel_id)
        for wheel_id in UNITY_WHEEL_OBJECTS.values()
    }
    seen = {wheel_id: 0 for wheel_id in wheel_targets}
    face_counts = {wheel_id: 0 for wheel_id in wheel_targets}
    wheel_counts = {wheel_id: [0, 0, 0] for wheel_id in wheel_targets}

    with ExitStack() as stack:
        body = stack.enter_context(body_temporary.open("w", encoding="utf-8"))
        wheel_streams = {
            wheel_id: stack.enter_context(path.open("w", encoding="utf-8"))
            for wheel_id, path in wheel_targets.items()
        }
        for wheel_id, stream in wheel_streams.items():
            stream.write("# Joint-local wheel mesh generated from Unity OBJ\n")
            stream.write("mtllib vehicle_visual.mtl\n")
            stream.write(f"o {wheel_id}_wheel_visual\n")

        vertex_count = 0
        uv_count = 0
        normal_count = 0
        vertex_base = 0
        uv_base = 0
        normal_base = 0
        current_wheel = None

        with source.open(encoding="utf-8", errors="strict") as stream:
            for line in stream:
                if line.startswith("o "):
                    current_wheel = _wheel_object(line[2:].strip())
                    if current_wheel is not None:
                        seen[current_wheel] += 1
                        vertex_base = vertex_count - wheel_counts[current_wheel][0]
                        uv_base = uv_count - wheel_counts[current_wheel][1]
                        normal_base = normal_count - wheel_counts[current_wheel][2]
                    body.write(line)
                    continue

                wheel_stream = (
                    wheel_streams[current_wheel]
                    if current_wheel is not None
                    else None
                )
                if line.startswith("v "):
                    vertex_count += 1
                    body.write(line)
                    if wheel_stream is not None:
                        wheel_counts[current_wheel][0] += 1
                        values = [float(value) for value in line.split()[1:4]]
                        local = [
                            value - center
                            for value, center in zip(values, centers[current_wheel])
                        ]
                        wheel_stream.write(f"v {_sequence(local)}\n")
                elif line.startswith("vt "):
                    uv_count += 1
                    body.write(line)
                    if wheel_stream is not None:
                        wheel_counts[current_wheel][1] += 1
                        wheel_stream.write(line)
                elif line.startswith("vn "):
                    normal_count += 1
                    body.write(line)
                    if wheel_stream is not None:
                        wheel_counts[current_wheel][2] += 1
                        wheel_stream.write(line)
                elif line.startswith("f ") and wheel_stream is not None:
                    wheel_stream.write(
                        _local_obj_face(line, vertex_base, uv_base, normal_base)
                    )
                    face_counts[current_wheel] += 1
                else:
                    body.write(line)
                    if wheel_stream is not None and line.startswith("usemtl "):
                        wheel_stream.write(line)

    for wheel_id in wheel_targets:
        if seen[wheel_id] < 1 or face_counts[wheel_id] == 0:
            raise ValueError(
                f"Unity OBJ wheel split failed for {wheel_id}: "
                f"objects={seen[wheel_id]}, faces={face_counts[wheel_id]}"
            )
    body_temporary.replace(body_target)


def _obj_index(value: str, item_count: int) -> int:
    """Resolve a positive or negative OBJ index to a zero-based index."""
    numeric = int(value)
    if numeric == 0:
        raise ValueError("OBJ indices cannot be zero")
    resolved = numeric - 1 if numeric > 0 else item_count + numeric
    if resolved < 0 or resolved >= item_count:
        raise ValueError(f"OBJ index is out of range: {value}")
    return resolved


def _simplify_obj_vertex_clusters(
    source: Path,
    grid_size_m: float,
    normal_bins: int = SIMULATION_LOD_NORMAL_BINS,
) -> dict[str, int]:
    """Build a deterministic visual LOD while retaining OBJ materials and UVs.

    Unity's CAD-oriented model contains many nearly coincident vertices. The
    simulation does not need those sub-millimetre details, so vertices with a
    similar position and normal are clustered per material. Degenerate and
    duplicate triangles created by clustering are removed. This changes only
    visual meshes; collision geometry, wheel joints and sensor frames remain
    generated from the canonical vehicle configuration.
    """
    if grid_size_m <= 0.0:
        raise ValueError("OBJ LOD grid size must be positive")
    if normal_bins <= 0:
        raise ValueError("OBJ LOD normal bin count must be positive")

    vertices: list[tuple[float, float, float]] = []
    uvs: list[tuple[float, float]] = []
    normals: list[tuple[float, float, float]] = []
    faces: list[tuple[str, str, int, int, int]] = []
    cluster_lookup: dict[tuple[Any, ...], int] = {}
    vertex_lookup: dict[tuple[int, int, str], int] = {}
    position_sums: list[list[float]] = []
    normal_sums: list[list[float]] = []
    cluster_uvs: list[tuple[float, float] | None] = []
    cluster_counts: list[int] = []
    seen_faces: set[tuple[Any, ...]] = set()
    object_name = "lod_visual"
    material_name = ""
    material_library = "vehicle_visual.mtl"
    input_face_count = 0

    def clustered_vertex(token: str) -> int:
        parts = token.split("/")
        vertex_index = _obj_index(parts[0], len(vertices))
        normal_index = vertex_index
        uv_index = _obj_index(parts[1], len(uvs)) if len(parts) > 1 and parts[1] else None
        if len(parts) > 2 and parts[2]:
            normal_index = _obj_index(parts[2], len(normals))
        cache_key = (vertex_index, normal_index, uv_index, material_name)
        existing = vertex_lookup.get(cache_key)
        if existing is not None:
            return existing

        position = vertices[vertex_index]
        normal = (
            normals[normal_index]
            if normal_index < len(normals)
            else (0.0, 0.0, 1.0)
        )
        cluster_key = (
            material_name,
            uvs[uv_index] if uv_index is not None else None,
            *(round(value / grid_size_m) for value in position),
            *(round(value * normal_bins) for value in normal),
        )
        cluster_index = cluster_lookup.get(cluster_key)
        if cluster_index is None:
            cluster_index = len(position_sums)
            cluster_lookup[cluster_key] = cluster_index
            position_sums.append(list(position))
            normal_sums.append(list(normal))
            cluster_uvs.append(uvs[uv_index] if uv_index is not None else None)
            cluster_counts.append(1)
        else:
            for axis in range(3):
                position_sums[cluster_index][axis] += position[axis]
                normal_sums[cluster_index][axis] += normal[axis]
            cluster_counts[cluster_index] += 1
        vertex_lookup[cache_key] = cluster_index
        return cluster_index

    with source.open(encoding="utf-8", errors="strict") as stream:
        for line in stream:
            if line.startswith("mtllib "):
                material_library = line[7:].strip()
            elif line.startswith("o "):
                object_name = line[2:].strip() or "lod_visual"
            elif line.startswith("usemtl "):
                material_name = line[7:].strip()
            elif line.startswith("v "):
                values = tuple(float(value) for value in line.split()[1:4])
                vertices.append(values)
            elif line.startswith("vn "):
                values = tuple(float(value) for value in line.split()[1:4])
                normals.append(values)
            elif line.startswith("vt "):
                uvs.append(tuple(float(value) for value in line.split()[1:3]))
            elif line.startswith("f "):
                tokens = line.split()[1:]
                if len(tokens) < 3:
                    continue
                input_face_count += len(tokens) - 2
                mapped = [clustered_vertex(token) for token in tokens]
                for index in range(1, len(mapped) - 1):
                    triangle = (mapped[0], mapped[index], mapped[index + 1])
                    if len(set(triangle)) < 3:
                        continue
                    signature = (material_name, *sorted(triangle))
                    if signature in seen_faces:
                        continue
                    seen_faces.add(signature)
                    faces.append((object_name, material_name, *triangle))

    if not faces:
        raise ValueError(f"OBJ LOD simplification removed every face: {source}")

    temporary = source.with_name(f".{source.name}.lod.tmp")
    with temporary.open("w", encoding="utf-8") as output:
        output.write("# Visual LOD generated for Gazebo and RViz\n")
        output.write(f"mtllib {material_library}\n")
        for position, count in zip(position_sums, cluster_counts):
            output.write(
                "v "
                + " ".join(_number(value / count) for value in position)
                + "\n"
            )
        for normal in normal_sums:
            length = math.sqrt(sum(value * value for value in normal)) or 1.0
            output.write(
                "vn "
                + " ".join(_number(value / length) for value in normal)
                + "\n"
            )
        uv_indices = {}
        for index, uv in enumerate(cluster_uvs):
            if uv is not None:
                uv_indices[index] = len(uv_indices) + 1
                output.write(f"vt {_sequence(uv)}\n")

        previous_object = None
        previous_material = None
        for current_object, current_material, first, second, third in faces:
            if current_object != previous_object:
                output.write(f"o {current_object}\n")
                previous_object = current_object
                previous_material = None
            if current_material and current_material != previous_material:
                output.write(f"usemtl {current_material}\n")
                previous_material = current_material
            output.write("f " + " ".join(
                f"{index + 1}/{uv_indices.get(index, '')}/{index + 1}"
                for index in (first, second, third)) + "\n")
    temporary.replace(source)
    return {
        "inputVertices": len(vertices),
        "outputVertices": len(position_sums),
        "inputFaces": input_face_count,
        "outputFaces": len(faces),
    }


def generate_sensor_mounts(config: dict[str, Any]) -> dict[str, Any]:
    result: dict[str, Any] = {
        "vehicle_id": config["vehicleId"],
        "base_link_reference": config["baseFrame"]["reference"],
    }
    for sensor in config["sensors"]:
        pose = effective_sensor_pose(sensor)
        item = {
            "parent_frame": config["baseFrame"]["frameId"],
            "child_frame": sensor.get("measurementFrameId") or sensor["frameId"],
            "xyz": pose["xyz"],
            "rpy": pose["rpy"],
            "model": sensor["model"],
        }
        if sensor.get("role"):
            item["role"] = sensor["role"]
        result[sensor["id"]] = item
    return result


