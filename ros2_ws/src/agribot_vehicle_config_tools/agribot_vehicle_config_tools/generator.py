                f"    <joint name=\"{wheel_id}_steering_joint\" type=\"revolute\"><pose relative_to=\"__model__\">{_sequence(wheel['position'])} 0 0 0</pose><parent>base_link</parent><child>{steering_id}</child><axis><xyz>0 0 1</xyz><limit><lower>-{_number(geometry['maxSteeringAngleRad'])}</lower><upper>{_number(geometry['maxSteeringAngleRad'])}</upper><effort>200</effort><velocity>1.5</velocity></limit></axis></joint>"
